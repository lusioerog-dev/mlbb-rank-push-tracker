export type HeroMetadata = (typeof HERO_CATALOG)[number];

export function normalizeHeroGameId(value: string | null | undefined) {
  if (!value || !/^\d+$/.test(value)) return null;
  return value.replace(/^0+(?=\d)/, "");
}

export function heroMetadataByGameId(value: string | null | undefined) {
  const gameId = normalizeHeroGameId(value);
  return gameId === null
    ? null
    : (HERO_CATALOG.find((hero) => hero.gameId === gameId) ?? null);
}

export type HeroIdentity = {
  name: string;
  gameId?: string | null | undefined;
};

export function heroDisplayName(hero: HeroIdentity | null | undefined) {
  return (
    heroMetadataByGameId(hero?.gameId)?.name ?? hero?.name ?? "Hero unavailable"
  );
}
